#!/usr/bin/env bash
# Usage: check-traces.sh <commit-range>   checks commit messages in the range and every tracked file
#        check-traces.sh --stdin          checks text piped in (PR title and body)
set -euo pipefail

pattern='\b(co-authored-by|claude|chatgpt|copilot|generated with|generated by|seamlessly|leverage|delve|it.s worth noting|this ensures that|in this pr we have)\b'
excluded=(':!SPEC.md' ':!.gitignore' ':!scripts/check-traces.sh' ':!scripts/check-traces.test.sh' ':!ui/src/shared/api/schema.ts')

if [[ "${1:-}" == "--stdin" ]]; then
  if grep -Eqi "$pattern"; then
    echo "Banned wording found in the pull request text."
    exit 1
  fi
  exit 0
fi

range=${1:?commit range required}
status=0

while read -r commit; do
  if git log -1 --format=%B "$commit" | grep -Eqi "$pattern"; then
    echo "Banned wording in commit message: $(git log -1 --format='%h %s' "$commit")"
    status=1
  fi
done < <(git rev-list "$range")

if git grep -IEin "$pattern" -- . "${excluded[@]}"; then
  echo "Banned wording found in the tracked files above."
  status=1
fi

exit $status
